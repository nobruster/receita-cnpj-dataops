select
    upper({{ txt('cnpj_basico') }})                          as cnpj_basico,
    upper({{ txt('cnpj_ordem') }})                           as cnpj_ordem,
    {{ txt('cnpj_dv') }}                                     as cnpj_dv,
    upper({{ txt('cnpj_basico') }}) || upper({{ txt('cnpj_ordem') }}) || {{ txt('cnpj_dv') }} as cnpj,
    {{ txt('identificador_matriz_filial') }}                 as identificador_matriz_filial,
    {{ txt('nome_fantasia') }}                               as nome_fantasia,
    lpad({{ txt('situacao_cadastral') }}, 2, '0')            as situacao_cadastral,
    {{ rfb_date('data_situacao_cadastral') }}                as data_situacao_cadastral,
    {{ rfb_date_invalida('data_situacao_cadastral') }}       as _data_situacao_invalida,
    lpad({{ txt('motivo_situacao_cadastral') }}, 2, '0')     as motivo_situacao_cadastral,
    {{ txt('nome_cidade_exterior') }}                        as nome_cidade_exterior,
    lpad({{ txt('pais') }}, 3, '0')                          as pais,
    {{ rfb_date('data_inicio_atividade') }}                  as data_inicio_atividade,
    {{ rfb_date_invalida('data_inicio_atividade') }}         as _data_inicio_invalida,
    {{ txt('cnae_fiscal_principal') }}                       as cnae_fiscal_principal,
    {{ txt('cnae_fiscal_secundaria') }}                      as cnae_fiscal_secundaria,
    {{ txt('tipo_logradouro') }}                             as tipo_logradouro,
    {{ txt('logradouro') }}                                  as logradouro,
    {{ txt('numero') }}                                      as numero,
    {{ txt('complemento') }}                                 as complemento,
    {{ txt('bairro') }}                                      as bairro,
    -- a Receita perde o zero à esquerda em ~0,1% dos CEPs (7 dígitos)
    case when regexp_full_match(trim(cep), '[0-9]{7}') then '0' || trim(cep) else {{ txt('cep') }} end as cep,
    upper({{ txt('uf') }})                                   as uf,
    lpad({{ txt('municipio') }}, 4, '0')                     as municipio,
    {{ txt('ddd_1') }} as ddd_1, {{ txt('telefone_1') }} as telefone_1,
    {{ txt('ddd_2') }} as ddd_2, {{ txt('telefone_2') }} as telefone_2,
    {{ txt('ddd_fax') }} as ddd_fax, {{ txt('fax') }} as fax,
    lower({{ txt('correio_eletronico') }})                   as correio_eletronico,
    {{ txt('situacao_especial') }}                           as situacao_especial,
    {{ rfb_date('data_situacao_especial') }}                 as data_situacao_especial,
    _arquivo, _competencia, _carregado_em
from {{ source('raw', 'raw_estabelecimentos') }}
